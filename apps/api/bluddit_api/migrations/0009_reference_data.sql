-- Cache only public Blizzard documents; credentials and OAuth tokens never persist here.
CREATE TABLE reference_cache (
    cache_key text PRIMARY KEY,
    document jsonb,
    fetched_at timestamptz,
    expires_at timestamptz,
    retry_at timestamptz,
    lease_token uuid,
    lease_until timestamptz
);
CREATE TABLE reference_entities (
    entity_kind text NOT NULL CHECK (entity_kind IN ('class', 'spec', 'profession', 'dungeon')),
    reference_id text NOT NULL,
    blizzard_id bigint,
    payload jsonb NOT NULL,
    active boolean NOT NULL DEFAULT false,
    PRIMARY KEY (entity_kind, reference_id),
    UNIQUE (entity_kind, blizzard_id)
);
